# One-time local database setup for NjangiTrust (docs/DECISIONS.md D2).
#
# Creates two roles and two databases on the local PostgreSQL server:
#   njangi_owner  owns the schema; used only by migrations
#   njangi_app    used by the API at runtime; UPDATE and DELETE on the ledger
#                 tables are revoked by a migration (spec 2.5)
#   njangitrust, njangitrust_test
# then writes apps/api/.env with freshly generated secrets.
#
# The postgres superuser password is read from PG_SUPERUSER_PASSWORD or asked
# for interactively. It is never written to disk.
param(
  [string]$PgBin = "C:\Program Files\PostgreSQL\16\bin",
  [string]$PgHost = "localhost",
  [int]$PgPort = 5432,
  [switch]$Force
)
$ErrorActionPreference = 'Stop'
$psql = Join-Path $PgBin 'psql.exe'
$envFile = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\.env'))

if ((Test-Path $envFile) -and -not $Force) {
  throw "$envFile already exists. Re-run with -Force to rotate the database passwords and rewrite it."
}

$superPassword = $env:PG_SUPERUSER_PASSWORD
if (-not $superPassword) {
  $secure = Read-Host 'postgres superuser password' -AsSecureString
  $superPassword = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
}

function New-Secret([int]$bytes = 32) {
  $buffer = New-Object byte[] $bytes
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
  -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

function Invoke-Sql([string]$database, [string]$sql) {
  $env:PGPASSWORD = $superPassword
  try {
    $sql | & $psql -h $PgHost -p $PgPort -U postgres -d $database -v ON_ERROR_STOP=1 -q -X
    if ($LASTEXITCODE -ne 0) { throw "psql failed on database $database" }
  } finally {
    Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
  }
}

$ownerPassword = New-Secret 24
$appPassword = New-Secret 24

Invoke-Sql 'postgres' @"
DO `$`$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'njangi_owner') THEN
    CREATE ROLE njangi_owner LOGIN CREATEDB PASSWORD '$ownerPassword';
  ELSE
    ALTER ROLE njangi_owner LOGIN CREATEDB PASSWORD '$ownerPassword';
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'njangi_app') THEN
    CREATE ROLE njangi_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$appPassword';
  ELSE
    ALTER ROLE njangi_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$appPassword';
  END IF;
END `$`$;
SELECT 'CREATE DATABASE njangitrust OWNER njangi_owner'
  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'njangitrust') \gexec
SELECT 'CREATE DATABASE njangitrust_test OWNER njangi_owner'
  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'njangitrust_test') \gexec
"@

foreach ($db in 'njangitrust', 'njangitrust_test') {
  Invoke-Sql 'postgres' @"
REVOKE ALL ON DATABASE $db FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE $db TO njangi_app;
"@
  Invoke-Sql $db @"
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO njangi_app;
ALTER DEFAULT PRIVILEGES FOR ROLE njangi_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO njangi_app;
ALTER DEFAULT PRIVILEGES FOR ROLE njangi_owner IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO njangi_app;
"@
}

$base = "${PgHost}:$PgPort"
$lines = @(
  '# Generated by apps/api/scripts/setup-db.ps1. Never commit this file.',
  'NODE_ENV=development',
  'PORT=3000',
  "DATABASE_URL=postgresql://njangi_app:$appPassword@$base/njangitrust",
  "MIGRATION_DATABASE_URL=postgresql://njangi_owner:$ownerPassword@$base/njangitrust",
  "TEST_DATABASE_URL=postgresql://njangi_app:$appPassword@$base/njangitrust_test",
  "TEST_MIGRATION_DATABASE_URL=postgresql://njangi_owner:$ownerPassword@$base/njangitrust_test",
  'REDIS_URL=redis://localhost:6379',
  "JWT_SECRET=$(New-Secret 48)",
  "JWT_REFRESH_SECRET=$(New-Secret 48)",
  'STORAGE_DRIVER=local',
  'STORAGE_LOCAL_DIR=.storage',
  "STORAGE_SIGNING_SECRET=$(New-Secret 32)",
  'S3_ENDPOINT=',
  'S3_BUCKET=',
  'S3_ACCESS_KEY=',
  'S3_SECRET_KEY=',
  'PAYMENT_PROVIDER=mock',
  'CAMPAY_USERNAME=',
  'CAMPAY_PASSWORD=',
  'CAMPAY_ENV=DEV',
  'FEE_SCHEDULE={"collection":100,"disbursement":500}',
  'OPENROUTER_API_KEY=',
  'OPENROUTER_MODEL=',
  'OPENROUTER_BASE_URL=https://openrouter.ai/api/v1',
  'APP_TIMEZONE=Africa/Douala',
  'PUBLIC_BASE_URL=http://localhost:3000',
  'WEB_ORIGINS=http://localhost:8081'
)
[IO.File]::WriteAllLines($envFile, $lines, (New-Object Text.UTF8Encoding $false))
Write-Host "Databases and roles ready. Wrote $envFile"

// Object storage (spec 2.12, D2). Phones upload and download directly with short-lived URLs; the
// server checks the real file type after upload. Two drivers: `local` (development, files on disk,
// HMAC-signed URLs served by the API) and `s3` (any S3-compatible service, presigned URLs).

/** Spec 2.12: read URLs are valid 5 minutes. */
export const DOWNLOAD_URL_TTL_SECONDS = 5 * 60;
export const UPLOAD_URL_TTL_SECONDS = 10 * 60;

export interface UploadUrl {
  url: string;
  method: 'PUT';
  /** Headers the client must send with the upload (the signed content type). */
  headers: Record<string, string>;
  expiresAt: Date;
}

export interface StorageProvider {
  readonly driver: 'local' | 's3';
  createUploadUrl(input: {
    key: string;
    contentType: string;
    maxBytes: number;
    expiresInSeconds?: number;
  }): Promise<UploadUrl>;
  createDownloadUrl(input: { key: string; expiresInSeconds?: number }): Promise<{ url: string; expiresAt: Date }>;
  /** Size of a stored object, or null if it doesn't exist. */
  stat(key: string): Promise<{ sizeBytes: number } | null>;
  /** The first bytes of an object, to check its real type. */
  readHead(key: string, bytes: number): Promise<Uint8Array | null>;
  remove(key: string): Promise<void>;
  /** For GET /health. */
  check(): Promise<boolean>;
}

/** Storage keys are generated by the server: `groups/<groupId>/<uuid>.<ext>`. */
const KEY = /^[a-z0-9][a-z0-9_-]*(\/[a-z0-9][a-z0-9_-]*)*(\.[a-z0-9]{1,8})?$/;

export function isValidStorageKey(key: string): boolean {
  return key.length <= 200 && KEY.test(key) && !key.includes('..');
}

export function assertStorageKey(key: string): void {
  if (!isValidStorageKey(key)) throw new Error('Invalid storage key');
}
